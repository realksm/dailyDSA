// Copies the few Solar icons the landing page uses out of @iconify-json/solar (a dev dependency)
// into src/landing/solar.ts, so the page needs no runtime icon request and no 8,700-icon JSON in the bundle.
// Run from apps/web after changing the list: node scripts/solar-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const set = require("@iconify-json/solar/icons.json");
const info = require("@iconify-json/solar/info.json");
const pkg = require("@iconify-json/solar/package.json");

const NAMES = {
  read: "document-text-linear",
  run: "play-linear",
  submit: "upload-minimalistic-linear",
  unlock: "lock-keyhole-unlocked-linear",
  hidden: "eye-closed-linear",
  calendar: "calendar-mark-linear",
  lesson: "book-2-linear",
  hint: "lightbulb-linear",
  judge: "cpu-linear",
  limits: "stopwatch-linear",
  streak: "fire-linear",
  archive: "archive-linear",
  invite: "ticket-linear",
  login: "login-3-linear",
  arrow: "arrow-right-linear",
  menu: "hamburger-menu-linear",
  close: "close-square-linear",
};

const lines = Object.entries(NAMES).map(([key, name]) => {
  const icon = set.icons[name];
  if (!icon) throw new Error(`Solar has no icon "${name}"`);
  return `  ${key}: ${JSON.stringify(icon.body)},`;
});

const out = `// Generated by scripts/solar-icons.mjs — do not edit by hand.
// Icons: Solar by ${info.author.name} (${info.author.url}), ${info.license.title} (${info.license.url}),
// via Iconify, @iconify-json/solar ${pkg.version}. Credited in the landing page footer.
export const SOLAR = {
${lines.join("\n")}
} as const;

export type SolarName = keyof typeof SOLAR;
`;

const target = new URL("../src/landing/solar.ts", import.meta.url);
let before = "";
try { before = readFileSync(target, "utf8"); } catch {}
if (before !== out) writeFileSync(target, out);
console.log(`solar.ts: ${lines.length} icons`);
